// [x; n] and Simd::splat for element types of 1 to 16 bytes, bool, char and small structs, n in 0..80,
// with a runtime and a constant element, returned, written through a pointer and at an offset inside
// a struct (guard bytes around it). Guards the 16-byte vector splat of repeats (cg_clif 925acac4).
#![feature(portable_simd)]
use std::fmt::Debug;
use std::hint::black_box as bb;

#[derive(Clone, Copy, PartialEq, Debug)]
#[repr(C)]
struct P(u8, u16);
#[derive(Clone, Copy, PartialEq, Debug)]
struct Q(u32);

trait K: Copy + PartialEq + Debug {
    const V: Self;
}
macro_rules! k { ($($t:ty = $v:expr),*) => { $(impl K for $t { const V: Self = $v; })* }; }
k!(u8 = 0xa5, i8 = -3, u16 = 0xa5c3, u32 = 0xdead_beef, u64 = 0x0123_4567_89ab_cdef,
   u128 = 0x0123_4567_89ab_cdef_fedc_ba98_7654_3210, f32 = 1.5, f64 = -2.25, bool = true,
   char = '\u{1F600}', usize = 0x1234_5678, P = P(0x77, 0x1234), Q = Q(7));

static mut FAILS: u32 = 0;
fn fail(what: &str, ty: &str, n: usize) {
    unsafe { FAILS += 1 }
    println!("FAIL {what} [{ty}; {n}]");
}

#[repr(C)]
struct G<T, const N: usize> {
    a: u8,
    arr: [T; N],
    b: u8,
}
#[inline(never)]
fn ret<T: K, const N: usize>(x: T) -> [T; N] {
    [x; N]
}
#[inline(never)]
fn ret_const<T: K, const N: usize>() -> [T; N] {
    [T::V; N]
}
#[inline(never)]
fn into<T: K, const N: usize>(p: &mut [T; N], x: T) {
    *p = [x; N];
}
#[inline(never)]
fn guard<T: K, const N: usize>(x: T) -> G<T, N> {
    G { a: 0x11, arr: [x; N], b: 0x22 }
}
#[inline(never)]
fn local<T: K, const N: usize>(x: T, i: usize) -> T {
    let a = bb([x; N]);
    a[i]
}

fn check<T: K, const N: usize>() {
    let ty = std::any::type_name::<T>();
    let x = bb(T::V);
    let ok = |a: &[T]| a.len() == N && a.iter().all(|e| *e == x);
    if !ok(&ret::<T, N>(x)) { fail("ret", ty, N) }
    if !ok(&ret_const::<T, N>()) { fail("const", ty, N) }
    let mut buf = bb([[x; N]; 3]);
    into(&mut buf[1], x);
    if !buf.iter().all(|a| ok(a)) { fail("into", ty, N) }
    let g = bb(guard::<T, N>(x));
    if g.a != 0x11 || g.b != 0x22 || !ok(&g.arr) { fail("guard", ty, N) }
    if (0..N).any(|i| local::<T, N>(x, i) != x) { fail("local", ty, N) }
}

macro_rules! lens { ($t:ty: $($n:literal),*) => { $(check::<$t, $n>();)* }; }

macro_rules! simd { ($t:ty = $v:expr; $($n:literal),*) => { $({
    #[inline(never)]
    fn s(x: $t) -> std::simd::Simd<$t, $n> { std::simd::Simd::splat(x) }
    let x: $t = bb($v);
    if !bb(s(x)).to_array().iter().all(|e| *e == x) { fail("simd", stringify!($t), $n) }
    let c = std::simd::Simd::<$t, $n>::splat($v);
    if !bb(c).to_array().iter().all(|e| *e == x) { fail("simd const", stringify!($t), $n) }
})* }; }

